import type { Field, Literal, Node, Spec } from "./spec.js"

const LUA_IDENT = /^[A-Za-z_][A-Za-z0-9_]*$/
const LUA_KEYWORDS = new Set([
  "and", "break", "do", "else", "elseif", "end", "false", "for", "function", "goto", "if", "in",
  "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while"
])
const TS_IDENT = /^[A-Za-z_$][A-Za-z0-9_$]*$/

const luaString = (s: string): string =>
  "'" + s.replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/\n/g, "\\n").replace(/\r/g, "\\r") + "'"

const luaLiteral = (v: Literal): string => (typeof v === "string" ? luaString(v) : String(v))
const luaKey = (k: string): string => (LUA_IDENT.test(k) && !LUA_KEYWORDS.has(k) ? k : `[${luaString(k)}]`)
const tsKey = (k: string): string => (TS_IDENT.test(k) ? k : JSON.stringify(k))
const comment = (text: string | undefined, prefix: string): string =>
  text ? text.split("\n").map((l) => `${prefix}${l}`).join("\n") + "\n" : ""

const header = (source: string, lineComment: string): string =>
  `${lineComment} Generated by rivo-fx gen from ${source}. Do not edit; change the schema file and run it again.\n`

// Lua ------------------------------------------------------------------------

const luaSchema = (node: Node, ns: string, indent = ""): string => {
  switch (node.kind) {
    case "string": {
      let s = "S.string"
      if (node.minLength !== undefined) s += `:minChars(${node.minLength})`
      if (node.maxLength !== undefined) s += `:maxChars(${node.maxLength})`
      return s
    }
    case "number":
    case "int": {
      let s = node.kind === "int" ? "S.int" : "S.number"
      if (node.min !== undefined) s += `:min(${node.min})`
      if (node.max !== undefined) s += `:max(${node.max})`
      return s
    }
    case "boolean":
      return "S.boolean"
    case "unknown":
      return "S.unknown"
    case "literal":
      return `S.literal(${node.values.map(luaLiteral).join(", ")})`
    case "array": {
      let s = `S.array(${luaSchema(node.items, ns, indent)})`
      if (node.minItems !== undefined) s += `:minItems(${node.minItems})`
      if (node.maxItems !== undefined) s += `:maxItems(${node.maxItems})`
      return s
    }
    case "record":
      return `S.record(S.string, ${luaSchema(node.values, ns, indent)})`
    case "struct": {
      if (node.fields.length === 0) return "S.struct {}"
      const inner = indent + "  "
      const fields = node.fields.map((f) => `${inner}${luaKey(f.name)} = ${luaSchema(f.node, ns, inner)}${f.optional ? ":optional()" : ""},`)
      return `S.struct {\n${fields.join("\n")}\n${indent}}`
    }
    case "tuple":
      return `S.tuple(${node.items.map((n) => luaSchema(n, ns, indent)).join(", ")})`
    case "union":
      return `S.union(${node.of.map((n) => luaSchema(n, ns, indent)).join(", ")})`
    case "ref":
      return `${ns}.${node.name}`
  }
}

const luaType = (node: Node, ns: string): string => {
  switch (node.kind) {
    case "string":
      return "string"
    case "number":
      return "number"
    case "int":
      return "integer"
    case "boolean":
      return "boolean"
    case "unknown":
      return "any"
    case "literal":
      return node.values.map((v) => (typeof v === "string" ? JSON.stringify(v) : String(v))).join("|")
    case "array": {
      const t = luaType(node.items, ns)
      return /[|]/.test(t) ? `(${t})[]` : `${t}[]`
    }
    case "record":
      return `table<string, ${luaType(node.values, ns)}>`
    case "struct":
      return `{ ${node.fields.map((f) => `${luaDocName(f.name)}${f.optional ? "?" : ""}: ${luaType(f.node, ns)}`).join(", ")} }`
    case "tuple":
      return `{ ${node.items.map((n, i) => `[${i + 1}]: ${luaType(n, ns)}`).join(", ")} }`
    case "union":
      return node.of.map((n) => luaType(n, ns)).join("|")
    case "ref":
      return `${ns}.${node.name}`
  }
}

const luaDocName = (k: string): string => (LUA_IDENT.test(k) ? k : `[${JSON.stringify(k)}]`)

const luaFieldLine = (f: Field, ns: string): string =>
  `---@field ${luaDocName(f.name)}${f.optional ? "?" : ""} ${luaType(f.node, ns)}${f.node.description ? ` ${f.node.description}` : ""}`

/**
 * A Lua file for `shared_script`: defines the global table `ns` holding one
 * Fx.S schema per name, with LuaLS classes for the decoded values.
 */
export const generateLua = (spec: Spec, opts: { namespace: string; source: string }): string => {
  const ns = opts.namespace
  let out = header(opts.source, "--")
  out += `-- Load after @rivo_fx/init.lua. Values decoded by ${ns}.<Name>:validate(v) match ---@class ${ns}.<Name>.\n`
  out += "local S = Fx.S\n\n"
  out += `${ns} = ${ns} or {}\n`
  for (const { name, node } of spec.schemas) {
    out += "\n" + comment(node.description, "---")
    if (node.kind === "struct") {
      out += `---@class ${ns}.${name}\n`
      for (const f of node.fields) out += luaFieldLine(f, ns) + "\n"
    } else {
      out += `---@alias ${ns}.${name} ${luaType(node, ns)}\n`
    }
    out += `---@type Fx.Schema<${ns}.${name}>\n`
    out += `${ns}.${name} = ${luaSchema(node, ns)}\n`
  }
  out += `\nreturn ${ns}\n`
  return out
}

// TypeScript -------------------------------------------------------------------

const tsSchema = (node: Node, indent = ""): string => {
  const checks = (base: string, list: string[]): string => (list.length ? `${base}.check(${list.join(", ")})` : base)
  switch (node.kind) {
    case "string":
      return checks("Schema.String", [
        ...(node.minLength !== undefined ? [`Schema.isMinCodePoints(${node.minLength})`] : []),
        ...(node.maxLength !== undefined ? [`Schema.isMaxCodePoints(${node.maxLength})`] : [])
      ])
    case "number":
    case "int":
      return checks(node.kind === "int" ? "Schema.Int" : "Schema.Finite", [
        ...(node.min !== undefined ? [`Schema.isGreaterThanOrEqualTo(${node.min})`] : []),
        ...(node.max !== undefined ? [`Schema.isLessThanOrEqualTo(${node.max})`] : [])
      ])
    case "boolean":
      return "Schema.Boolean"
    case "unknown":
      return "Schema.Unknown"
    case "literal":
      return node.values.length === 1
        ? `Schema.Literal(${JSON.stringify(node.values[0])})`
        : `Schema.Literals([${node.values.map((v) => JSON.stringify(v)).join(", ")}])`
    case "array":
      return checks(`Schema.Array(${tsSchema(node.items, indent)})`, [
        ...(node.minItems !== undefined ? [`Schema.isMinLength(${node.minItems})`] : []),
        ...(node.maxItems !== undefined ? [`Schema.isMaxLength(${node.maxItems})`] : [])
      ])
    case "record":
      return `Schema.Record(Schema.String, ${tsSchema(node.values, indent)})`
    case "struct": {
      if (node.fields.length === 0) return "Schema.Struct({})"
      const inner = indent + "  "
      const fields = node.fields.map((f) => {
        const s = tsSchema(f.node, inner)
        return `${inner}${tsKey(f.name)}: ${f.optional ? `Schema.optionalKey(${s})` : s}`
      })
      return `Schema.Struct({\n${fields.join(",\n")}\n${indent}})`
    }
    case "tuple":
      return `Schema.Tuple([${node.items.map((n) => tsSchema(n, indent)).join(", ")}])`
    case "union":
      return `Schema.Union([${node.of.map((n) => tsSchema(n, indent)).join(", ")}])`
    case "ref":
      return node.name
  }
}

/** A TypeScript module of Effect schemas (and their types) for JS resources. */
export const generateEffect = (spec: Spec, opts: { source: string }): string => {
  let out = header(opts.source, "//")
  out += 'import { Schema } from "effect"\n'
  for (const { name, node } of spec.schemas) {
    out += "\n" + comment(node.description, "// ")
    out += `export const ${name} = ${tsSchema(node)}\n`
    out += `export type ${name} = typeof ${name}.Type\n`
  }
  return out
}

const tsType = (node: Node): string => {
  switch (node.kind) {
    case "string":
      return "string"
    case "number":
    case "int":
      return "number"
    case "boolean":
      return "boolean"
    case "unknown":
      return "unknown"
    case "literal":
      return node.values.map((v) => JSON.stringify(v)).join(" | ")
    case "array":
      return `ReadonlyArray<${tsType(node.items)}>`
    case "record":
      return `{ readonly [key: string]: ${tsType(node.values)} }`
    case "struct":
      return `{ ${node.fields.map((f) => `readonly ${tsKey(f.name)}${f.optional ? "?" : ""}: ${tsType(f.node)}`).join("; ")} }`
    case "tuple":
      return `readonly [${node.items.map(tsType).join(", ")}]`
    case "union":
      return node.of.map(tsType).join(" | ")
    case "ref":
      return node.name
  }
}

/**
 * Plain TypeScript types, for NUI pages that do not use Effect. Readonly, like
 * Effect's decoded types, so values move between the two either way.
 */
export const generateTypes = (spec: Spec, opts: { source: string }): string => {
  let out = header(opts.source, "//")
  for (const { name, node } of spec.schemas) {
    out += "\n" + comment(node.description, "/** ").replace(/\n$/, " */\n")
    if (node.kind === "struct") {
      out += `export interface ${name} {\n`
      for (const f of node.fields) {
        if (f.node.description) out += `  /** ${f.node.description} */\n`
        out += `  readonly ${tsKey(f.name)}${f.optional ? "?" : ""}: ${tsType(f.node)}\n`
      }
      out += "}\n"
    } else {
      out += `export type ${name} = ${tsType(node)}\n`
    }
  }
  return out
}
